"""Transparent end-of-day paper trading engine. No brokerage connectivity."""
import os
from datetime import datetime, timezone
import numpy as np
import pandas as pd
import yfinance as yf
from sqlalchemy import create_engine, text

START_CASH = 10000.0
WATCH = ['VOO','QQQ','SPY','IWM','TLT','IEF','SHY','GLD','BTC-USD','ETH-USD','AAPL','MSFT','NVDA','AMZN','GOOGL','META','JPM','XLF','XLK','XLV']
BENCH = ['VOO','QQQ']
FEE_BPS = 5  # modeled 0.05% execution friction each trade

def db():
    url = os.environ.get('DATABASE_URL','sqlite:///paper_lab.db')
    if url.startswith('postgres://'): url='postgresql://'+url[len('postgres://'):]
    return create_engine(url, pool_pre_ping=True)

def init(engine):
    with engine.begin() as c:
        c.execute(text('CREATE TABLE IF NOT EXISTS trades (id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, run_date TEXT NOT NULL, ticker TEXT NOT NULL, side TEXT NOT NULL, shares DOUBLE PRECISION NOT NULL, price DOUBLE PRECISION NOT NULL, fee DOUBLE PRECISION NOT NULL, reason TEXT NOT NULL)') if engine.dialect.name=='postgresql' else text('CREATE TABLE IF NOT EXISTS trades (id INTEGER PRIMARY KEY AUTOINCREMENT, run_date TEXT NOT NULL, ticker TEXT NOT NULL, side TEXT NOT NULL, shares REAL NOT NULL, price REAL NOT NULL, fee REAL NOT NULL, reason TEXT NOT NULL)'))
        c.execute(text('CREATE TABLE IF NOT EXISTS snapshots (run_date TEXT PRIMARY KEY, equity DOUBLE PRECISION NOT NULL, cash DOUBLE PRECISION NOT NULL, benchmark_voo DOUBLE PRECISION, benchmark_qqq DOUBLE PRECISION, note TEXT NOT NULL)'))
        c.execute(text('CREATE TABLE IF NOT EXISTS decisions (run_date TEXT NOT NULL, ticker TEXT NOT NULL, score DOUBLE PRECISION NOT NULL, action TEXT NOT NULL, reason TEXT NOT NULL, PRIMARY KEY(run_date,ticker))'))
        c.execute(text('CREATE TABLE IF NOT EXISTS config (key TEXT PRIMARY KEY, value TEXT NOT NULL)'))

def read(engine, table): return pd.read_sql_query(text('SELECT * FROM '+table),engine)

def prices(tickers, period='1y'):
    raw=yf.download(tickers,period=period,interval='1d',auto_adjust=True,progress=False,threads=True)
    if raw.empty: raise RuntimeError('No price data returned. Try again later.')
    close=raw['Close'] if isinstance(raw.columns,pd.MultiIndex) else raw[['Close']].rename(columns={'Close':tickers[0]})
    return close.sort_index().ffill()

def holdings(trades):
    h={}
    cash=START_CASH
    for _,r in trades.sort_values('id').iterrows():
        qty=float(r.shares)*(1 if r.side=='BUY' else -1)
        h[r.ticker]=h.get(r.ticker,0)+qty
        cash-=qty*float(r.price)+float(r.fee)
    return cash,{k:v for k,v in h.items() if v>1e-7}

def score_frame(close):
    out=[]
    for ticker in close.columns:
        s=close[ticker].dropna()
        if len(s)<210: continue
        p=float(s.iloc[-1]); ma50=float(s.tail(50).mean()); ma200=float(s.tail(200).mean())
        ret20=float(p/s.iloc[-21]-1); vol=float(s.pct_change().tail(60).std()*np.sqrt(252))
        score=(2 if p>ma200 else -2)+(1 if ma50>ma200 else -1)+np.clip(ret20*20,-2,2)-min(vol,1.5)
        out.append(dict(ticker=ticker,price=p,score=round(float(score),3),trend=p>ma200,ret20=ret20,vol=vol,reason=f'Close ${p:.2f}; 200d trend {"positive" if p>ma200 else "negative"}; 20d return {ret20:+.1%}; annualized volatility {vol:.1%}'))
    return pd.DataFrame(out).sort_values('score',ascending=False) if out else pd.DataFrame()

def run(engine, dry_run=False):
    init(engine)
    close=prices(WATCH)
    date=str(close.index[-1].date())
    old=read(engine,'snapshots')
    if date in set(old.run_date.astype(str)) and not dry_run: return {'status':'already recorded','date':date}
    sf=score_frame(close)
    if sf.empty: raise RuntimeError('Not enough historical market data to generate signals')
    trades=read(engine,'trades'); cash,h=holdings(trades)
    latest={k:float(close[k].dropna().iloc[-1]) for k in close.columns if not close[k].dropna().empty}
    equity=cash+sum(q*latest.get(k,0) for k,q in h.items())
    # At most 4 positions, max 25% per holding, keep 10% cash buffer. No leverage/shorting.
    eligible=sf[(sf.score>0.8)&(sf.trend)].head(4)
    target=set(eligible.ticker)
    orders=[]
    for ticker,q in h.items():
        if ticker not in target and ticker in latest:
            orders.append((ticker,'SELL',q,latest[ticker],f'No longer in top positive-trend candidates'))
    for ticker,side,q,p,reason in orders:
        cash+=q*p*(1-FEE_BPS/10000); h.pop(ticker,None)
    # Set positions near 22.5% of current equity, never exceeding cash reserve.
    for _,r in eligible.iterrows():
        ticker=r.ticker;p=latest[ticker]
        existing=h.get(ticker,0)
        desired=max(0,0.225*equity/p-existing)
        qty=np.floor(desired*10000)/10000
        qty=min(qty,max(0,(cash-max(0.1*equity,0))/(p*(1+FEE_BPS/10000))))
        qty=np.floor(qty*10000)/10000
        if qty*p>=5:
            orders.append((ticker,'BUY',qty,p,r.reason));cash-=qty*p*(1+FEE_BPS/10000);h[ticker]=existing+qty
    equity=cash+sum(q*latest.get(k,0) for k,q in h.items())
    # Benchmark anchored to first recorded trading date; cannot backfill earlier prices.
    def benchmark(t):
        if t not in latest: return None
        if old.empty: return START_CASH
        with engine.connect() as c:
            x=c.execute(text('SELECT value FROM config WHERE key=:k'),{'k':'base_'+t}).scalar()
        return START_CASH*latest[t]/float(x) if x else START_CASH
    bvoo=benchmark('VOO');bqqq=benchmark('QQQ')
    if dry_run:return {'date':date,'orders':orders,'equity':equity,'cash':cash,'signals':sf.to_dict('records')}
    with engine.begin() as c:
        for t in BENCH:
            if old.empty and t in latest:
                c.execute(text('INSERT INTO config(key,value) VALUES (:k,:v)'),{'k':'base_'+t,'v':str(latest[t])})
        for _,r in sf.iterrows():
            c.execute(text('INSERT INTO decisions(run_date,ticker,score,action,reason) VALUES (:d,:t,:s,:a,:r)'),{'d':date,'t':r.ticker,'s':float(r.score),'a':'CANDIDATE' if r.ticker in target else 'HOLD/AVOID','r':r.reason})
        for ticker,side,qty,p,reason in orders:
            c.execute(text('INSERT INTO trades(run_date,ticker,side,shares,price,fee,reason) VALUES (:d,:t,:s,:q,:p,:f,:r)'),{'d':date,'t':ticker,'s':side,'q':float(qty),'p':p,'f':qty*p*FEE_BPS/10000,'r':reason})
        c.execute(text('INSERT INTO snapshots(run_date,equity,cash,benchmark_voo,benchmark_qqq,note) VALUES (:d,:e,:c,:v,:q,:n)'),{'d':date,'e':equity,'c':cash,'v':bvoo,'q':bqqq,'n':'End-of-day close proxy; orders modeled at observed close, not executable fills'})
    return {'status':'saved','date':date,'orders':orders,'equity':equity,'cash':cash}

if __name__=='__main__':
    e=db(); print(run(e))
